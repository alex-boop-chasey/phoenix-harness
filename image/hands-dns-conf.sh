#!/bin/bash
# Prints the dnsmasq config for the agent container's DNS allowlist (run by init-firewall.sh as root).
#   hands-dns-conf.sh <ipset> <upstream-ipv4>... < hostnames
# stdin: one exact lowercase hostname per line; blank lines and #-comments are skipped.
# Only listed names (and their subdomains: dnsmasq matches by suffix) are forwarded upstream, and the
# addresses they resolve to are added to <ipset> at query time. Every other name gets NXDOMAIN locally.
# Fails closed (exit 2, no output) on any invalid hostname, upstream or set name, so nothing a spec
# writes into allowed-domains can inject a dnsmasq directive.
set -euo pipefail

die() { echo "hands-dns-conf: $*" >&2; exit 2; }

[ $# -ge 2 ] || die "usage: hands-dns-conf.sh <ipset> <upstream-ipv4>... < hostnames"
set_name=$1; shift
[[ "$set_name" =~ ^[A-Za-z0-9_-]{1,31}$ ]] || die "invalid ipset name: ${set_name@Q}"

upstreams=()
for ip in "$@"; do
  [[ "$ip" =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$ ]] || die "invalid upstream: ${ip@Q}"
  for o in "${BASH_REMATCH[@]:1}"; do
    [[ "$o" =~ ^(0|[1-9][0-9]*)$ ]] && [ "$o" -le 255 ] || die "invalid upstream: ${ip@Q}"
  done
  case "$ip" in 0.*|127.0.0.1) die "upstream would loop or is unroutable: $ip";; esac
  upstreams+=("$ip")
done

valid_host() {
  local h=$1 label
  [ "${#h}" -ge 1 ] && [ "${#h}" -le 253 ] || return 1
  [[ "$h" == *.* ]] || return 1
  local IFS=.
  local -a labels
  read -r -a labels <<< "$h"
  # read drops a trailing empty field, so count dots to catch "a..b" and "a.b."
  [ "${#labels[@]}" -eq "$(( $(tr -cd . <<< "$h" | wc -c) + 1 ))" ] || return 1
  for label in "${labels[@]}"; do
    [[ "$label" =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]] || return 1
  done
  [[ ! "${labels[-1]}" =~ ^[0-9]+$ ]]   # an all-numeric TLD is an IP literal, not a name
}

declare -A seen=()
hosts=()
n=0
while IFS= read -r line || [ -n "$line" ]; do
  n=$((n + 1))
  line=${line%$'\r'}
  line="${line#"${line%%[![:space:]]*}"}"
  line="${line%"${line##*[![:space:]]}"}"
  [ -z "$line" ] && continue
  [[ "$line" == \#* ]] && continue
  valid_host "$line" || die "line $n: ${line@Q} is not an exact lowercase hostname"
  [ -n "${seen[$line]:-}" ] && continue
  seen[$line]=1
  hosts+=("$line")
done

cat <<EOF
# generated by hands-dns-conf.sh: only the names below resolve; everything else is NXDOMAIN
port=53
listen-address=127.0.0.1
bind-interfaces
user=root
group=root
no-resolv
no-hosts
no-poll
domain-needed
bogus-priv
filter-AAAA
cache-size=1000
pid-file=/run/hands-dns/dnsmasq.pid
local=/#/
EOF
for h in "${hosts[@]}"; do
  for ip in "${upstreams[@]}"; do echo "server=/$h/$ip"; done
  echo "ipset=/$h/$set_name"
done
